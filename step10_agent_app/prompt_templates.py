SYSTEM_PROMPT = """你是一名资深企业舆情分析专家，擅长从社交媒体数据中洞察行业趋势、用户情绪和商业机会。

你的分析必须严格基于提供的数据，禁止编造任何数据或事实。如果数据不足，请明确说明"数据不足，无法判断"。

输出格式为 Markdown，语言专业简洁，适合企业决策者阅读。"""


def build_daily_report_prompt(context: str, report_date: str = None) -> str:
    """
    构建微博行业舆情日报 Prompt

    Args:
        context: 从 API 获取的结构化数据上下文
        report_date: 日报日期

    Returns:
        完整的 Prompt 文本
    """
    date_str = report_date or "今日"

    return f"""请根据以下微博数据分析数据，生成一份《微博行业舆情日报》。

## 数据上下文

{context}

## 输出要求

请严格按照以下结构输出 Markdown 格式日报：

# 微博行业舆情日报（{date_str}）

## 1. 今日热点 TOP5

从热点微博数据中提炼最受关注的 5 个事件，每个事件包含：
- 事件标题（来自微博内容）
- 博主
- 互动数据（点赞/评论/转发/热度指数）
- 影响范围分析（基于互动量和博主粉丝数判断）
- 用户关注原因（基于内容和评论情感分析推断）

## 2. AI行业趋势

分析关键词趋势数据，重点关注：
- 豆包、飞书、Agent、大模型、AI办公、ChatGPT 等关键词的提及量变化
- 哪个关键词热度最高，为什么
- 行业讨论的核心议题是什么
- 技术方向的变化趋势

## 3. 用户情绪分析

基于情感分析数据：
- 正面/中性/负面比例
- 正面反馈集中在哪些方面
- 负面问题有哪些（结合高频负面观点词）
- 用户最关注的痛点是什么
- 情绪变化趋势（如果有时间序列数据）

## 4. 重点账号分析

基于用户影响力数据：
- 哪些账号影响力最高（粉丝量/互动量）
- 这些账号为什么产生影响力（内容类型/发布频率/互动质量）
- 哪些账号值得企业关注或合作
- KOL 分布特征

## 5. 行业机会洞察

综合以上分析，输出：
- 企业应该关注什么（3-5 条具体建议）
- 下一步动作建议（可执行的具体措施）
- 需要警惕的风险或负面舆情
- 潜在的商业机会点

## 重要约束

1. 所有数据必须来自上方提供的 API 数据，禁止编造
2. 引用具体数字时必须与数据一致
3. 如果某个板块数据不足，请明确说明"该板块数据不足"
4. 分析要有洞察，不要简单罗列数据
5. 输出纯 Markdown，不要包含代码块标记
"""


